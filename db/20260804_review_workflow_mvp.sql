alter table public.audio_records
  add column if not exists respondent_key text;

create table if not exists public.annotation_cases (
  id bigint generated by default as identity primary key,
  task_id integer not null references public.final_tasks(id) on delete cascade,
  language text not null check (language in ('台語', '客語')),
  state text not null default '待指派',
  assigned_to text,
  assigned_by text,
  assigned_at timestamptz,
  claim_by text,
  claim_token uuid,
  claim_until timestamptz,
  current_version_no integer not null default 0,
  source_stamp text not null default '',
  legacy_unreviewed boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (task_id, language)
);

create table if not exists public.annotation_versions (
  id bigint generated by default as identity primary key,
  case_id bigint not null references public.annotation_cases(id) on delete cascade,
  version_no integer not null,
  version_kind text not null default 'draft' check (version_kind in ('draft', 'final', 'legacy')),
  fields jsonb not null default '{}'::jsonb,
  created_by text not null,
  created_at timestamptz not null default now(),
  unique (case_id, version_no)
);

create table if not exists public.audio_assessments (
  id bigint generated by default as identity primary key,
  task_id integer not null references public.final_tasks(id) on delete cascade,
  language text not null check (language in ('台語', '客語')),
  audio_record_id bigint not null references public.audio_records(id) on delete cascade,
  assessor_account text not null,
  respondent_key text not null,
  decision text not null check (decision in ('可用', '不可用', '待追問')),
  reason text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.proofing_events (
  id bigint generated by default as identity primary key,
  case_id bigint not null references public.annotation_cases(id) on delete cascade,
  action text not null,
  actor_account text not null,
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.writeback_jobs (
  id bigint generated by default as identity primary key,
  case_id bigint not null references public.annotation_cases(id) on delete cascade,
  version_id bigint not null references public.annotation_versions(id),
  task_id integer not null references public.final_tasks(id),
  source_id text not null,
  source_table text not null,
  language text not null check (language in ('台語', '客語')),
  version_no integer not null,
  source_stamp text not null default '',
  payload jsonb not null default '{}'::jsonb,
  idempotency_key text not null unique,
  status text not null default 'queued' check (status in ('queued', 'processing', 'retry', 'succeeded', 'failed')),
  attempt_count integer not null default 0,
  last_error text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  completed_at timestamptz
);

create table if not exists public.writeback_errors (
  id bigint generated by default as identity primary key,
  job_id bigint references public.writeback_jobs(id) on delete set null,
  case_id bigint references public.annotation_cases(id) on delete set null,
  error_code text not null default 'unknown',
  error_message text not null,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists annotation_cases_assignment_idx
  on public.annotation_cases (assigned_to, state);
create index if not exists annotation_cases_claim_idx
  on public.annotation_cases (claim_until);
create index if not exists annotation_versions_case_idx
  on public.annotation_versions (case_id, version_no desc);
create index if not exists audio_assessments_audio_idx
  on public.audio_assessments (audio_record_id, assessor_account, created_at desc);
create index if not exists proofing_events_case_idx
  on public.proofing_events (case_id, created_at desc);
create index if not exists writeback_jobs_status_idx
  on public.writeback_jobs (status, updated_at);

