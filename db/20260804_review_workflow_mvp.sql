select
  ft.id,
  lang.language,
  'legacy_unreviewed',
  old_review.assigned_to,
  old_review.assigned_by,
  old_review.assigned_at,
  case when lang.language = '台語' then coalesce(src.t_updated_at, '') else coalesce(src.h_updated_at, '') end,
