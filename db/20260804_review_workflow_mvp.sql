create or replace function public.workflow_actor_role_(p_actor_account text)
returns text
language sql
security definer
set search_path to 'public'
as $$
  select lower(trim(i.role))
  from public.investigators i
  where lower(trim(i.account)) = lower(trim(p_actor_account))
    and i.is_active = true
  limit 1;
$$;

create or replace function public.get_review_workflow_queue(p_actor_account text)
returns setof public.app_review_workflow_queue
language plpgsql
security definer
set search_path to 'public'
as $function$
declare
  v_role text := public.workflow_actor_role_(p_actor_account);
begin
  if v_role not in ('admin', 'proofreader') then
    raise exception 'proofreader permission required';
  end if;

  return query
  select q.*
  from public.app_review_workflow_queue q
  where v_role = 'admin'
     or q.assigned_to = p_actor_account
     or q.claim_by = p_actor_account
  order by q.updated_at desc nulls last, q.case_id;
end;
$function$;

create or replace function public.assign_review_case(p_case_id bigint, p_assignee text, p_actor_account text)
returns public.annotation_cases
language plpgsql
security definer
set search_path to 'public'
as $function$
declare
  v_role text := public.workflow_actor_role_(p_actor_account);
  v_case public.annotation_cases;
  v_class_name text;
begin
  if v_role <> 'admin' then raise exception 'admin permission required'; end if;
  if nullif(trim(p_assignee), '') is null then raise exception 'assignee is required'; end if;

  select class_name into v_class_name
  from public.app_review_workflow_queue where case_id = p_case_id;
  if not found then raise exception 'review case not found'; end if;

  update public.annotation_cases
  set assigned_to = trim(p_assignee), assigned_by = p_actor_account, assigned_at = now(),
      state = case when v_class_name = '書面標注' then '書面標注中' else '錄音中' end,
      claim_by = null, claim_token = null, claim_until = null, updated_at = now()
  where id = p_case_id
  returning * into v_case;

  insert into public.proofing_events(case_id, action, actor_account, payload)
  values (p_case_id, 'reassign', p_actor_account, jsonb_build_object('assigned_to', trim(p_assignee)));
  return v_case;
end;
$function$;

create or replace function public.claim_review_case(p_case_id bigint, p_actor_account text)
returns public.annotation_cases
language plpgsql
security definer
set search_path to 'public'
as $function$
declare
  v_role text := public.workflow_actor_role_(p_actor_account);
  v_case public.annotation_cases;
begin
  if v_role not in ('admin', 'proofreader') then raise exception 'proofreader permission required'; end if;

  update public.annotation_cases
  set claim_by = p_actor_account, claim_token = gen_random_uuid(), claim_until = now() + interval '30 minutes',
      state = case when state = '待校對' then '校對中' else state end, updated_at = now()
  where id = p_case_id
    and (v_role = 'admin' or assigned_to = p_actor_account)
    and (claim_until is null or claim_until <= now() or claim_by = p_actor_account)
    and state <> '已完成'
  returning * into v_case;
  if not found then raise exception 'case unavailable or already claimed'; end if;

  insert into public.proofing_events(case_id, action, actor_account)
  values (p_case_id, 'claim', p_actor_account);
  return v_case;
end;
$function$;

create or replace function public.release_review_case(p_case_id bigint, p_actor_account text)
returns public.annotation_cases
language plpgsql
security definer
set search_path to 'public'
as $function$
declare
  v_role text := public.workflow_actor_role_(p_actor_account);
  v_case public.annotation_cases;
begin
  if v_role not in ('admin', 'proofreader') then raise exception 'proofreader permission required'; end if;

  update public.annotation_cases
  set claim_by = null, claim_token = null, claim_until = null,
      state = case when current_version_no > 0 then '待校對' else state end,
      updated_at = now()
  where id = p_case_id
    and (v_role = 'admin' or claim_by = p_actor_account)
  returning * into v_case;
  if not found then raise exception 'case is not claimed by actor'; end if;

  insert into public.proofing_events(case_id, action, actor_account)
  values (p_case_id, 'release', p_actor_account);
  return v_case;
end;
$function$;

create or replace function public.save_annotation_version(
  p_case_id bigint, p_actor_account text, p_fields jsonb
)
returns public.annotation_versions
language plpgsql
security definer
set search_path to 'public'
as $function$
declare
  v_role text := public.workflow_actor_role_(p_actor_account);
  v_case public.annotation_cases;
  v_version public.annotation_versions;
  v_next integer;
begin
  if v_role not in ('admin', 'user', 'annotator', 'audio_assessor') then raise exception 'annotation permission required'; end if;
  select * into v_case from public.annotation_cases where id = p_case_id;
  if not found then raise exception 'review case not found'; end if;
  if v_role <> 'admin' and v_case.assigned_to <> p_actor_account then raise exception 'case assignment required'; end if;

  select coalesce(max(version_no), 0) + 1 into v_next
  from public.annotation_versions where case_id = p_case_id;

  insert into public.annotation_versions(case_id, version_no, version_kind, fields, created_by)
  values (p_case_id, v_next, 'draft', coalesce(p_fields, '{}'::jsonb), p_actor_account)
  returning * into v_version;

  update public.annotation_cases
  set current_version_no = v_next,
      state = case when state in ('錄音中', '書面標注中', 'legacy_unreviewed') then '待校對' else state end,
      updated_at = now()
  where id = p_case_id;
  return v_version;
end;
$function$;

create or replace function public.submit_audio_assessment(
  p_task_id integer, p_language text, p_audio_record_id bigint,
  p_assessor_account text, p_respondent_key text, p_decision text, p_reason text default ''
)
returns public.audio_assessments
language plpgsql
security definer
set search_path to 'public'
as $function$
declare
  v_role text := public.workflow_actor_role_(p_assessor_account);
  v_assessment public.audio_assessments;
begin
  if v_role not in ('admin', 'user', 'annotator', 'audio_assessor') or v_role = 'proofreader' then
    raise exception 'audio assessment permission required';
  end if;
  if p_language not in ('台語', '客語') then raise exception 'unsupported language'; end if;
  if p_decision not in ('可用', '不可用', '待追問') then raise exception 'unsupported audio decision'; end if;
  if nullif(trim(p_respondent_key), '') is null then raise exception 'respondent key is required'; end if;

  if not exists (
    select 1 from public.audio_records ar
    where ar.id = p_audio_record_id and ar.task_id = p_task_id and ar.language = p_language and ar.unlinked_at is null
  ) then raise exception 'audio record not found or unlinked'; end if;

  insert into public.audio_assessments(task_id, language, audio_record_id, assessor_account, respondent_key, decision, reason)
  values (p_task_id, p_language, p_audio_record_id, p_assessor_account, trim(p_respondent_key), p_decision, coalesce(p_reason, ''))
  returning * into v_assessment;
  return v_assessment;
end;
$function$;

create or replace function public.approve_review_case(p_case_id bigint, p_actor_account text)
returns public.writeback_jobs
language plpgsql
security definer
set search_path to 'public'
as $function$
declare
  v_role text := public.workflow_actor_role_(p_actor_account);
  q record;
  v_job public.writeback_jobs;
  v_key text;
  v_stamp text;
begin
  if v_role not in ('admin', 'proofreader') then raise exception 'proofreader permission required'; end if;
  select * into q from public.app_review_workflow_queue where case_id = p_case_id;
  if not found then raise exception 'review case not found'; end if;
  if v_role <> 'admin' and (q.claim_by <> p_actor_account or q.claim_until is null or q.claim_until <= now()) then
    raise exception 'active proofreader claim required';
  end if;
  if q.version_id is null or coalesce(q.annotation_fields, '{}'::jsonb) = '{}'::jsonb then
    raise exception 'annotation draft is required';
  end if;
  if not q.audio_gate_passed then raise exception 'two different respondents with usable audio are required'; end if;

  v_stamp := coalesce(q.current_sheet_stamp, '');
  v_key := q.case_id::text || ':' || q.current_version_no::text || ':' || coalesce(v_stamp, 'no-source-stamp');

  update public.annotation_cases
  set state = '已完成', updated_at = now()
  where id = p_case_id;

  insert into public.proofing_events(case_id, action, actor_account, payload)
  values (p_case_id, 'approve', p_actor_account, jsonb_build_object(
    'version_id', q.version_id, 'version_no', q.current_version_no,
    'audio_gate_passed', q.audio_gate_passed
  ));

  insert into public.writeback_jobs(
    case_id, version_id, task_id, source_id, source_table, language,
    version_no, source_stamp, payload, idempotency_key
  ) values (
    q.case_id, q.version_id, q.task_id, q.source_id, q.source_table, q.language,
    q.current_version_no, v_stamp, q.annotation_fields, v_key
  ) on conflict (idempotency_key) do update set updated_at = now()
  returning * into v_job;
  return v_job;
end;
$function$;

create or replace function public.complete_review_writeback(p_job_id bigint, p_source_stamp text)
returns boolean
language plpgsql
security definer
set search_path to 'public'
as $function$
begin
  update public.writeback_jobs
  set status = 'succeeded', completed_at = now(), updated_at = now(), last_error = ''
  where id = p_job_id
    and source_stamp = coalesce(p_source_stamp, '')
    and status in ('queued', 'processing', 'retry');
  return found;
end;
$function$;

create or replace function public.fail_review_writeback(
  p_job_id bigint, p_error_code text, p_error_message text, p_details jsonb default '{}'::jsonb
)
returns boolean
language plpgsql
security definer
set search_path to 'public'
as $function$
declare
  v_case_id bigint;
  v_attempts integer;
begin
  select case_id, attempt_count into v_case_id, v_attempts
  from public.writeback_jobs where id = p_job_id for update;
  if not found then return false; end if;

  update public.writeback_jobs
  set attempt_count = attempt_count + 1,
      status = case when attempt_count + 1 >= 5 then 'failed' else 'retry' end,
      last_error = coalesce(p_error_message, ''), updated_at = now()
  where id = p_job_id;

  insert into public.writeback_errors(job_id, case_id, error_code, error_message, details)
  values (p_job_id, v_case_id, coalesce(p_error_code, 'unknown'), coalesce(p_error_message, ''), coalesce(p_details, '{}'::jsonb));
  return true;
end;
$function$;

